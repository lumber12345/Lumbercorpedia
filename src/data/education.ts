export const ALL_COURSES: Course[] = DEGREES.flatMap((d) => d.courses);

export const degreeByCode = (code: DegreeCode): Degree | undefined => DEGREES.find((d) => d.code === code);

export const courseByCode = (code: string): Course | undefined =>
  ALL_COURSES.find((x) => x.code.toUpperCase() === code.toUpperCase());

export function degreeTotals(degree: Degree) {
  const weeks = degree.courses.reduce((sum, x) => sum + x.weeks, 0);
  const cost = degree.courses.reduce((sum, x) => sum + x.cost, 0);
  const manual = degree.courses.reduce((sum, x) => sum + x.manual, 0);
  const intelligence = degree.courses.reduce((sum, x) => sum + x.intelligence, 0);
  const endurance = degree.courses.reduce((sum, x) => sum + x.endurance, 0);
  return { weeks, cost, manual, intelligence, endurance };
}

/** Topological order of a degree's courses (prerequisites first). */
export function courseOrder(degree: Degree): Course[] {
  const remaining = [...degree.courses];
  const done = new Set<string>();
  const out: Course[] = [];
  let guard = 0;
  while (remaining.length && guard < 500) {
    guard += 1;
    const next = remaining.find((course) => course.prereqs.every((p) => done.has(p)));
    if (!next) break;
    out.push(next);
    done.add(next.code);
    remaining.splice(remaining.indexOf(next), 1);
  }
  return out;
}

/**
 * Education time reduction (patch #334, April 2024): reductions are additive,
 * not multiplicative. Merits cap at 20%, WSU stock block 10%, Education
 * principal job 10%. Job points (Fitness Center / Hair Salon) and the Book of
 * Carols shave hours off a course in progress rather than a percentage.
 */
export function reducedWeeks(weeks: number, meritPercent: number, wsu: boolean, principal: boolean): number {
  const reduction = Math.min(20, Math.max(0, meritPercent)) / 100 + (wsu ? 0.1 : 0) + (principal ? 0.1 : 0);
  return Math.max(0, weeks * (1 - Math.min(0.4, reduction)));
}
