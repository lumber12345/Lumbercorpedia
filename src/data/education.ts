/**
 * Education dataset.
 *
 * Two degrees (Biology, Computer Science) are modelled course-by-course from
 * the torn wiki tables — every cost, prerequisite, working-stat reward and
 * length in weeks is verified. The remaining ten degrees carry their verified
 * unlocks and perk list, with their course tables flagged `verified: false` so
 * the UI can mark them as incomplete rather than guessing numbers.
 */

export interface Course {
  code: string;
  name: string;
  degree: DegreeCode;
  prereqs: string[];
  cost: number;
  manual: number;
  intelligence: number;
  endurance: number;
  weeks: number;
  unlock?: string;
}

export type DegreeCode =
  | 'BIO'
  | 'BUS'
  | 'CBT'
  | 'CMT'
  | 'GEN'
  | 'HAF'
  | 'HIS'
  | 'LAW'
  | 'MTH'
  | 'PSY'
  | 'DEF'
  | 'SPT';

export interface Degree {
  code: DegreeCode;
  name: string;
  /** Bachelor course code, where known. */
  bachelor?: string;
  /** Verified list of what finishing the degree unlocks / grants. */
  payoff: string[];
  /** Perks spread across the degree's courses. */
  perks: string[];
  verified: boolean;
  courses: Course[];
  courseCount?: number;
  notes?: string;
}

